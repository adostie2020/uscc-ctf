#!/usr/bin/env bash
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
board="$root/challenges/BOARD.md"
{
  echo "# Team Board"; echo
  echo "_Generated by \`tools/update-board.sh\` — do not edit by hand._"; echo
  echo "| Category | Challenge | Points | Owner | Status |"
  echo "|----------|-----------|--------|-------|--------|"
  find "$root/challenges" -mindepth 2 -maxdepth 2 -type d | sort | while read -r d; do
    r="$d/README.md"; [[ -f "$r" ]] || continue
    cat="$(basename "$(dirname "$d")")"
    name="$(grep -m1 -E '^# ' "$r" | sed -E 's/^# +//')"
    points="$(grep -m1 -E '^- \*\*Points:\*\*' "$r" | sed -E 's/^- \*\*Points:\*\* *//')"
    owner="$(grep -m1 -E '^- \*\*Owner:\*\*' "$r" | sed -E 's/^- \*\*Owner:\*\* *//')"
    status="$(grep -m1 -E '^- \*\*Status:\*\*' "$r" | sed -E 's/^- \*\*Status:\*\* *([^ <]+).*/\1/')"
    echo "| $cat | $name | $points | $owner | $status |"
  done
} > "$board"
echo "Updated BOARD.md"
