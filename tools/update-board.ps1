$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot

$ctf = $env:CTF
if (-not $ctf) {
    $activeFile = Join-Path $root "ctfs/.active"
    if (Test-Path $activeFile) { $ctf = (Get-Content $activeFile -TotalCount 1).Trim() }
}
if (-not $ctf) { Write-Error "no active CTF: run tools/new-ctf.ps1 or set `$env:CTF"; exit 1 }
$chalRoot = Join-Path $root "ctfs/$ctf/challenges"
if (-not (Test-Path $chalRoot)) { Write-Error "no challenges dir: $chalRoot"; exit 1 }

$rows = @()
Get-ChildItem -Path $chalRoot -Directory | Where-Object { $_.Name -ne "" } | ForEach-Object {
    $cat = $_.Name
    Get-ChildItem -Path $_.FullName -Directory | ForEach-Object {
        $readme = Join-Path $_.FullName "README.md"
        if (Test-Path $readme) {
            $c = Get-Content $readme -Raw -Encoding UTF8
            $name   = if ($c -match '(?m)^#[ \t]+(.+?)\s*$')                     { $Matches[1].Trim() } else { $_.Name }
            $points = if ($c -match '(?m)^-\s+\*\*Points:\*\*[ \t]*(.*?)\s*$')    { $Matches[1].Trim() } else { '' }
            $status = if ($c -match '(?m)^-\s+\*\*Status:\*\*[ \t]*([^\s<]+)')    { $Matches[1].Trim() } else { 'untouched' }
            $owner  = if ($c -match '(?m)^-\s+\*\*Owner:\*\*[ \t]*(.*?)\s*$')     { $Matches[1].Trim() } else { '' }
            $rows += [pscustomobject]@{ Category=$cat; Name=$name; Points=$points; Owner=$owner; Status=$status }
        }
    }
}
$lines = @()
$lines += "# Team Board"
$lines += ""
$lines += "_Generated by ``tools/update-board`` — do not edit by hand._"
$lines += ""
$lines += "| Category | Challenge | Points | Owner | Status |"
$lines += "|----------|-----------|--------|-------|--------|"
$rowsArray = @($rows)
[Array]::Sort($rowsArray, [Comparison[object]]{
    param($a, $b)
    $c = [string]::Compare($a.Category, $b.Category, [StringComparison]::OrdinalIgnoreCase)
    if ($c -ne 0) { return $c }
    [string]::Compare($a.Name, $b.Name, [StringComparison]::OrdinalIgnoreCase)
})
foreach ($r in $rowsArray) {
    $lines += "| $($r.Category) | $($r.Name) | $($r.Points) | $($r.Owner) | $($r.Status) |"
}
$board = Join-Path $root "ctfs/$ctf/BOARD.md"
[System.IO.File]::WriteAllText($board, (($lines -join "`n") + "`n"), (New-Object System.Text.UTF8Encoding($false)))
Write-Host ("Updated {0} ({1} challenges)" -f $board, $rows.Count)
