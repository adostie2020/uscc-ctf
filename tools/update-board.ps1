$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$chalRoot = Join-Path $root "challenges"
$rows = @()
Get-ChildItem -Path $chalRoot -Directory | Where-Object { $_.Name -ne "" } | ForEach-Object {
    $cat = $_.Name
    Get-ChildItem -Path $_.FullName -Directory | ForEach-Object {
        $readme = Join-Path $_.FullName "README.md"
        if (Test-Path $readme) {
            $c = Get-Content $readme -Raw
            $name   = if ($c -match '(?m)^#\s+(.+?)\s*$')                     { $Matches[1].Trim() } else { $_.Name }
            $points = if ($c -match '(?m)^-\s+\*\*Points:\*\*\s*(.*?)\s*$')    { $Matches[1].Trim() } else { '' }
            $status = if ($c -match '(?m)^-\s+\*\*Status:\*\*\s*([^\s<]+)')    { $Matches[1].Trim() } else { 'untouched' }
            $owner  = if ($c -match '(?m)^-\s+\*\*Owner:\*\*\s*(.*?)\s*$')     { $Matches[1].Trim() } else { '' }
            $rows += [pscustomobject]@{ Category=$cat; Name=$name; Points=$points; Owner=$owner; Status=$status }
        }
    }
}
$lines = @()
$lines += "# Team Board"
$lines += ""
$lines += "_Generated by ``tools/update-board.ps1`` — do not edit by hand._"
$lines += ""
$lines += "| Category | Challenge | Points | Owner | Status |"
$lines += "|----------|-----------|--------|-------|--------|"
foreach ($r in ($rows | Sort-Object Category, Name)) {
    $lines += "| $($r.Category) | $($r.Name) | $($r.Points) | $($r.Owner) | $($r.Status) |"
}
$absoluteBoardPath = Join-Path $chalRoot "BOARD.md"
[System.IO.File]::WriteAllText($absoluteBoardPath, ($lines -join "`n"), (New-Object System.Text.UTF8Encoding($false)))
Write-Host ("Updated BOARD.md ({0} challenges)" -f $rows.Count)
